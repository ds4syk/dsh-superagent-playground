DATA_ROOT = Path(os.environ.get("BOP_DATA_ROOT", "/mnt/storage1/syk/data/bop"))
DATASET = sys.argv[1] if len(sys.argv) > 1 else "lm"
ROOT = DATA_ROOT / DATASET
OUT = Path(os.environ.get("BOP_OUT_DIR", str(HERE / "results" / DATASET)))
