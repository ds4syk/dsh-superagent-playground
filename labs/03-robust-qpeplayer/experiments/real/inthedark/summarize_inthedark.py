#!/usr/bin/env python3
"""Render results/inthedark_main.md from the run JSONs (no hand-typed numbers)."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
RES = HERE / "results"
CONFIGS = [("inthedark_dense", "run_000002", "dense SGBM"),
           ("inthedark_sparse", "run_000002", "sparse triangulation"),
           ("inthedark_run12_dense", "run_000012", "dense SGBM")]
METHODS = ("Kabsch", "RANSAC-1000", "RANSAC-adaptive", "IRLS-GM", "GNC-GM")


def load(name):
    return json.loads((RES / f"{name}.json").read_text())


def main():
    lines = ["# In-The-Dark: measured results (real data, composed official GT)", "",
             "Generated by `summarize_inthedark.py` from `results/*.json`.", "",
             "Front-end label: **hand-written SIFT + StereoSGBM dense disparity (or sparse",
             "left-right triangulation)**, the same `stereo_vo.py` code as the KITTI fallback.",
             "Not the SDPR VGG/UNet front-end. GT: repeat `transforms_spatial.txt` x teach",
             "`transforms_temporal.txt`, conjugated into the camera frame (protocol in README).",
             "", "## Per-configuration summary", "",
             "| config | run | pairs | inliers med [min,max] | corr med | depth med | GT \\|t\\| med | "
             "GNC rot | GNC trans | success@0.1 m | wall |",
             "|-|-|-|-|-|-|-|-|-|-|-|"]
    for name, run, label in CONFIGS:
        d = load(name)
        rows = [r for r in d["pairs"] if not r.get("skipped")]
        inl = [r["inlier_rate"] for r in rows]
        g = [r["methods"]["GNC-GM"] for r in rows]
        lines.append(
            f"| {label} | {run} | {len(rows)} | {np.median(inl)*100:.1f}% "
            f"[{min(inl)*100:.1f}, {max(inl)*100:.1f}] | {np.median([r['n'] for r in rows]):.0f} | "
            f"{np.median([r['med_depth_m'] for r in rows]):.1f} m | "
            f"{np.median([r['gt_trans'] for r in rows]):.3f} m | "
            f"{np.median([x['rot_deg'] for x in g]):.3f}° | "
            f"{np.median([x['trans_m'] for x in g]):.3f} m | "
            f"{100*np.mean([x['success'] for x in g]):.0f}% | {d['wall_s']:.1f} s |")

    for name, run, label in CONFIGS:
        d = load(name)
        rows = [r for r in d["pairs"] if not r.get("skipped")]
        lines += ["", f"## Robust layer: {label} ({run}, {len(rows)} pairs, c={d['c']} m)", "",
                  "| method | med rot (°) | med trans (m) | success@0.1 m | success@0.25 m | p50 (ms) | p95 (ms) | max (ms) |",
                  "|-|-|-|-|-|-|-|-|"]
        for m in METHODS:
            rs = [r["methods"][m] for r in rows]
            t = [x["time_ms"] for x in rs]
            lines.append(f"| {m} | {np.median([x['rot_deg'] for x in rs]):.3f} | "
                         f"{np.median([x['trans_m'] for x in rs]):.3f} | "
                         f"{100*np.mean([x['success'] for x in rs]):.0f}% | "
                         f"{100*np.mean([x['success_loose'] for x in rs]):.0f}% | "
                         f"{np.median(t):.1f} | {np.percentile(t, 95):.1f} | {max(t):.1f} |")
        fl = [r["floor"] for r in rows]
        lines.append(f"| floor (GT-inlier Kabsch) | {np.median([x['rot_deg'] for x in fl]):.3f} | "
                     f"{np.median([x['trans_m'] for x in fl]):.3f} | "
                     f"{100*np.mean([x['success'] for x in fl]):.0f}% | "
                     f"{100*np.mean([x['success_loose'] for x in fl]):.0f}% | – | – | – |")
        res_in = np.median([r["med_resid_inlier"] for r in rows])
        res_out = np.median([r["med_resid_outlier"] for r in rows])
        lines += ["", f"Natural inlier residual (c={d['c']} m): {res_in:.3f} m inlier side, "
                      f"{res_out:.3f} m outlier side; correspondence count {min(r['n'] for r in rows)}"
                      f"-{max(r['n'] for r in rows)}."]

    lines += ["", "## Protocol validation (verify_inthedark.py)", "",
              "| run | pairs | GT reproj (px) | inverse (px) | identity (px) | vehicle-frame (px) | median row dy |",
              "|-|-|-|-|-|-|-|"]
    for vrun in ("run_000002", "run_000012"):
        v = json.loads((RES / f"verify_{vrun}.json").read_text())
        rows = v["pairs"]
        lines.append(
            f"| {vrun} | {len(rows)} | {np.median([r['reproj_gt_px'] for r in rows]):.2f} | "
            f"{np.median([r['reproj_inverse_px'] for r in rows]):.2f} | "
            f"{np.median([r['reproj_identity_px'] for r in rows]):.2f} | "
            f"{np.median([r['reproj_vehicle_frame_px'] for r in rows]):.2f} | "
            f"{np.median([r['median_row_dy_px'] for r in rows]):.2f} px |")
    lines += ["", "All checks pass on both runs (`checks` block in the JSONs).", "",
              "## Limitations", "",
              "1. Both measured runs are **daylight** (left-image mean intensity median 133 / 131,"
              " sky visible, official metadata lists run_000002 as morning/sunny), so this validates"
              " the format, calibration and GT protocol on real In-The-Dark archives, **not**"
              " night-time robustness.",
              "2. The front-end is the hand-written SIFT+SGBM stereo front-end; the SDPR VGG/UNet"
              " front-end is not exercised here.",
              "3. GT itself is the official registration output (spatial matches from place"
              " recognition + ICP); its per-pair noise is ~0.3-1.4 px equivalent, so the 0.01-0.02 m"
              " errors should be read as 'at the GT noise floor', not as absolute accuracy.",
              "4. Only 15 consecutive pairs per configuration (single deterministic instance each);"
              " no injected outliers, no trials."]
    out = RES / "inthedark_main.md"
    out.write_text("\n".join(lines) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
