OUT.mkdir(parents=True, exist_ok=True)

N = 30
P_CON = 16
NOISE_PX = 1.0
BIAS_PX = [10.0, 20.0, 30.0]
MAX_IMG = int(os.environ.get("BOP_MAX_IMG", "2"))
FRAMES = sorted([d.name for d in (ROOT / "test").iterdir() if d.is_dir()])[:int(os.environ.get("BOP_MAX_FRAMES", "9"))]
OBJ_IDS = [int(x) for x in os.environ["BOP_OBJ_IDS"].split(",")] if os.environ.get("BOP_OBJ_IDS") else None
PLANE_CALIB = os.environ.get("BOP_PLANE_CALIB", "always")
SEED = int(os.environ.get("BOP_SEED", "20261127"))


def wilson(k, n, z=1.959963984540054):
    """95% Wilson score interval for k successes out of n."""
    if n == 0:
        return float("nan"), float("nan"), float("nan")
    p = k / n
    den = 1.0 + z * z / n
    center = (p + z * z / (2 * n)) / den
    half = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / den
    return p, max(0.0, center - half), min(1.0, center + half)


def mcnemar_exact(a, b):
    """Two-sided exact McNemar test on discordant counts a (0->1) and b (1->0)."""
    if a + b == 0:
        return 1.0, a, b
    return float(binomtest(a, a + b, 0.5).pvalue), a, b


def load_model(obj_id):
    p = ROOT / "models" / f"obj_{obj_id:06d}.ply"
    v = PlyData.read(str(p))["vertex"]
    return np.stack([np.asarray(v[a], dtype=float) for a in "xyz"], axis=1) * 0.001


def backproject(depth, K):
    h, w = depth.shape
    fx, fy = K[0, 0], K[1, 1]
    cx, cy = K[0, 2], K[1, 2]
    us, vs = np.meshgrid(np.arange(w), np.arange(h))
    X = (us - cx) / fx * depth
    Y = (vs - cy) / fy * depth
    Z = depth
    return np.stack([X, Y, Z], axis=-1)


def fit_table_plane(depth, mask, bbox, K, rng):
    x, y, w, h = bbox
    bg = (~mask) & (depth > 0)
    reg = np.zeros_like(bg)
    x0, y0 = max(0, x - 40), max(0, y - 40)
    x1, y1 = min(bg.shape[1], x + w + 40), min(bg.shape[0], y + h + 40)
    reg[y0:y1, x0:x1] = True
    ys, xs = np.where(bg & reg)
    if len(xs) < 100:
        return None
    idx = rng.choice(len(xs), min(4000, len(xs)), replace=False)
    X = backproject(depth, K)[ys[idx], xs[idx]]
    X = X[np.isfinite(X).all(axis=1)]
    best = None
    for _ in range(300):
        p = X[rng.choice(len(X), 3, replace=False)]
        n = np.cross(p[1] - p[0], p[2] - p[0])
        if np.linalg.norm(n) < 1e-9:
            continue
        n = n / np.linalg.norm(n)
        d = -n @ p[0]
        inl = np.abs(X @ n + d) < 0.005
        if best is None or inl.sum() > best[0]:
            best = (inl.sum(), n, d, X[inl])
    if best is None:
        return None
    _, n, d, inl = best
    # refit by least squares on inliers
    c = inl.mean(0)
    u, s, vt = np.linalg.svd(inl - c)
    n = vt[-1]
    d = -n @ c
    return n, d


def project(K, X):
    uv = (K @ X.T).T
    return uv[:, :2] / uv[:, 2:3]



def _gap(rows, key_j="J", key_b="shor"):
    return [r[key_j] - r[key_b] for r in rows
            if np.isfinite(r.get(key_b, np.nan)) and np.isfinite(r.get(key_j, np.nan))]


def _gap_line(name, vals):
    v = np.asarray(vals, dtype=float)
    if v.size == 0:
        return f"- {name}: n/a"
    return (f"- {name}: min {v.min():+.3e}, median {np.median(v):+.3e}, "
            f"max {v.max():+.3e}, negative {int((v < 0).sum())}/{v.size}")


def _rate_line(label, flags, caveat=""):
    flags = list(flags)
    if not flags:
        return f"- {label}: n/a"
    k = int(sum(bool(c) for c in flags))
    p, lo, hi = wilson(k, len(flags))
    return (f"- {label}: {100*p:.1f}% (95% CI {100*lo:.1f}-{100*hi:.1f}%, "
            f"k={k}/{len(flags)}){caveat}")


def write_table(rows, meta):
    """Render main_table.md from raw rows (also used by BOP_TABLE_ONLY=1)."""
    wall = float(meta.get("wall_s", float("nan")))
    dsname = {"lm": "LINEMOD", "lmo": "LM-O", "ycbv": "YCB-Video"}.get(
        meta.get("dataset"), meta.get("dataset", "?"))
    lines = [f"# BOP {dsname}: constrained PnP on real object meshes / real table planes\n",
             "Controlled layer experiment: the 2D-3D correspondences are 30 model vertices\n"
             "projected at the GT pose, then perturbed by pixel noise + downward pixel bias.\n"
             "This is NOT a learned detector; no end-to-end perception claim is made.\n",
             f"N={N}, P_CON={P_CON}, noise={NOISE_PX}px, bias={BIAS_PX}px\n",
             f"frames={len(meta.get('frames', []))}, max_img={meta.get('max_img')}, "
             f"obj_ids={meta.get('obj_ids')}, plane_calib={meta.get('plane_calib')}, "
             f"seed={meta.get('seed')}\n",
             "trial = (frame, image, object, bias) pose; the four methods share it. "
             "95% CI = Wilson score interval.\n",
             "CERTIFICATION CAVEAT: a sound lower bound needs Shor <= J, so the one-sided flag\n"
             "(J - Shor <= 1e-6) also accepts Shor > J and is an UPPER BOUND on the sound rate.\n"
             "The two-sided |J - Shor| <= 1e-6 count is reported next to it. SCS is not\n"
             "dual-feasible, so neither number is yet a rigorous certificate; a dual-repair\n"
             "pass is required before quoting a certified rate.\n"]
    for method in ["Unconstrained", "Soft penalty", "Projection", "ALM-QPEP"]:
        rs = [r for r in rows if r["method"] == method]
        if not rs:
            continue
        n = len(rs)
        lines.append(f"## {method}\n")
        lines.append(f"- trials: {n}")
        lines.append(f"- penetration median: {np.median([r['pen_mm'] for r in rs]):.2f} mm")
        lines.append(f"- rot median: {np.median([r['rot_deg'] for r in rs]):.2f} deg")
        lines.append(f"- trans median: {np.median([r['trans_mm'] for r in rs]):.2f} mm")
        lines.append(f"- feasible: {100*np.mean([r['feas'] for r in rs]):.1f}%")
        feas = [bool(r["feas"]) for r in rs]
        base = [np.isfinite(r.get("shor", np.nan)) for r in rs]
        rlt = [np.isfinite(r.get("shor_rlt", np.nan)) for r in rs]
        c1 = [f and b and (r["J"] - r["shor"] <= 1e-6) for f, b, r in zip(feas, base, rs)]
        c2 = [f and b and abs(r["J"] - r["shor"]) <= 1e-6 for f, b, r in zip(feas, base, rs)]
        c1r = [f and b and (r["J"] - r["shor_rlt"] <= 1e-6) for f, b, r in zip(feas, rlt, rs)]
        c2r = [f and b and abs(r["J"] - r["shor_rlt"]) <= 1e-6 for f, b, r in zip(feas, rlt, rs)]
        lines.append(_rate_line("certified, one-sided (UPPER BOUND)", c1))
        lines.append(_rate_line("certified, two-sided (necessary condition)", c2))
        lines.append(_rate_line("certified + RLT, one-sided (UPPER BOUND)", c1r))
        lines.append(_rate_line("certified + RLT, two-sided (necessary condition)", c2r))
        lines.append(_gap_line("gap J-Shor", _gap(rs)))
        lines.append(_gap_line("gap J-Shor(RLT)", _gap(rs, key_b="shor_rlt")))
        if len(c1) == len(c1r):
            b = sum(1 for a, c in zip(c1, c1r) if (not a) and c)
            c = sum(1 for a, cc in zip(c1, c1r) if a and (not cc))
            pval, b, c = mcnemar_exact(b, c)
            lines.append(f"- RLT paired gain, one-sided: {100*(b-c)/max(len(c1),1):+.1f} pp "
                         f"(0->1: {b}, 1->0: {c}, exact McNemar p={pval:.3g})")
            b2 = sum(1 for a, c in zip(c2, c2r) if (not a) and c)
            c2n = sum(1 for a, cc in zip(c2, c2r) if a and (not cc))
            pval2, b2, c2n = mcnemar_exact(b2, c2n)
            lines.append(f"- RLT paired gain, two-sided: {100*(b2-c2n)/max(len(c2),1):+.1f} pp "
                         f"(0->1: {b2}, 1->0: {c2n}, exact McNemar p={pval2:.3g})")
        ts = [r["time_ms"] / 1000.0 for r in rs]
        lines.append(f"- solve runtime (4 solvers): {np.sum(ts):.1f} s ({np.mean(ts):.2f} s/trial)")
        lines.append("")
    lines.append(f"Total wall clock: {wall:.1f} s; n_poses={meta.get('n_poses')}; "
                 f"mean plane {meta.get('t_plane_mean_s') or float('nan'):.2f} s, "
                 f"solve {meta.get('t_solve_mean_s') or float('nan'):.2f} s, "
                 f"Shor {meta.get('t_cert_mean_s') or float('nan'):.2f} s, "
                 f"Shor+RLT {meta.get('t_cert_rlt_mean_s') or float('nan'):.2f} s per pose; "
                 f"wall/trial {wall / max(len(rows) // 4, 1):.2f} s.\n")
    (OUT / "main_table.md").write_text("\n".join(lines) + "\n")
    print("wrote", OUT / "main_table.md", "trials", len(rows) // 4)


def main():
    if os.environ.get("BOP_TABLE_ONLY") == "1":
        write_table(json.load(open(OUT / "raw.json")), json.load(open(OUT / "meta.json")))
        return
    wall0 = time.perf_counter()
    rng = np.random.default_rng(SEED)
    # object ids: explicit env override, else the three most frequent in FRAMES
    from collections import Counter
    cnt = Counter()
    for frame in FRAMES:
        gt_all = json.load(open(ROOT / "test" / frame / "scene_gt.json"))
        for gt in gt_all.values():
            for g in gt:
                cnt[g["obj_id"]] += 1
    obj_ids = OBJ_IDS if OBJ_IDS is not None else [oid for oid, _ in cnt.most_common(3)]
    print("dataset", DATASET, "frames", FRAMES, "objects", obj_ids,
          "max_img", MAX_IMG, "plane_calib", PLANE_CALIB, flush=True)
    models = {oid: load_model(oid) for oid in obj_ids}
    rows = []
    t_plane_all, t_solve_all, t_cert_all, t_cert_rlt_all = [], [], [], []
    n_poses = 0
    for frame in FRAMES:
        fdir = ROOT / "test" / frame
        gt_all = json.load(open(fdir / "scene_gt.json"))
        info_all = json.load(open(fdir / "scene_gt_info.json"))
        cam_all = json.load(open(fdir / "scene_camera.json"))
        n_img = 0
        # sorted by numeric image id: "first MAX_IMG views", not JSON insertion order
        for img in sorted(gt_all, key=int):
            if n_img >= MAX_IMG:
                break
            n_img += 1
            gt = gt_all[img]
            info = info_all[img]
            cam = cam_all[img]
            K = np.array(cam["cam_K"]).reshape(3, 3)
            imgz = f"{int(img):06d}"
            depth = np.asarray(Image.open(fdir / "depth" / f"{imgz}.png"), dtype=float) * 0.001
            for k, g in enumerate(gt):
                oid = g["obj_id"]
                if oid not in models:
                    continue
                if info[k]["visib_fract"] < 0.4:
                    continue
                mask = np.asarray(Image.open(fdir / "mask" / f"{imgz}_{k:06d}.png")) > 0
                t0 = time.perf_counter()
                plane = fit_table_plane(depth, mask, info[k]["bbox_visib"], K, rng)
                t_plane = time.perf_counter() - t0
                if plane is None:
                    continue
                n, d = plane
                R = np.array(g["cam_R_m2c"]).reshape(3, 3)
                t = np.array(g["cam_t_m2c"]) * 0.001
                V = models[oid]
                x_gt = (R @ V.T).T + t
                # orient plane normal toward the object
                if n @ x_gt.mean(0) + d < 0:
                    n, d = -n, -d
                # calibrate the support plane to the GT contact: after this the
                # lowest GT vertex sits 1e-4 m above the plane, so the GT pose is
                # strictly feasible and the downward bias is what creates
                # penetration.  "if_penetrating" is the legacy run_linemod rule.
                gmin = (x_gt @ n + d).min()
                if PLANE_CALIB == "always":
                    d = d - gmin + 1e-4
                elif PLANE_CALIB == "if_penetrating":
                    if gmin < 0:
                        d = d - gmin + 1e-4
                else:
                    raise ValueError(f"unknown BOP_PLANE_CALIB={PLANE_CALIB}")
                n_poses += 1
                for bias_px in BIAS_PX:
                    t0 = time.perf_counter()
                    idx = rng.choice(len(V), N, replace=False)
                    P = V[idx]
                    x = (R @ P.T).T + t
                    uv = project(K, x)
                    uv = uv + rng.normal(scale=NOISE_PX, size=uv.shape) + np.array([0.0, bias_px])
                    U = np.linalg.inv(K) @ np.vstack([uv.T, np.ones(len(uv))])
                    U = U.T
                    U = U / np.linalg.norm(U, axis=1, keepdims=True)
                    M0, D0, G0 = core.build_objective(P, U)
                    # constraints: lowest P_CON vertices along the table normal
                    order = np.argsort(x_gt @ n + d)
                    A, B = [], []
                    for j in order[:P_CON]:
                        a, b = core.c_plane(V[j], n, d)
                        A.append(a); B.append(b)
                    A = np.array(A); B = np.array(B)
                    # unconstrained
                    Ju, q_u, t_u = core.solve_qp_global(M0, D0, G0, n_starts=32, rng=np.random.default_rng(1))
                    # soft / projection / ALM
                    try:
                        soft = core.soft_penalty(M0, D0, G0, A, B, 1e3, q_u, t_u, n_starts=8, rng=rng)
                        q_s, t_s = soft["q"], soft["t"]
                    except Exception:
                        q_s, t_s = q_u, t_u
                    try:
                        proj = core.project_feasible(M0, D0, G0, A, B, q_u, t_u, n_starts=4, rng=rng)
                        q_p, t_p = proj["q"], proj["t"]
                    except Exception:
                        q_p, t_p = q_u, t_u
                    alm = core.alm_qpep(M0, D0, G0, A, B, q_u, t_u, rho0=10.0, n_starts=6, rng=rng)
                    q_a, t_a = alm["q"], alm["t"]
                    t_solve = time.perf_counter() - t0
                    for name, q, tt in [("Unconstrained", q_u, t_u), ("Soft penalty", q_s, t_s),
                                        ("Projection", q_p, t_p), ("ALM-QPEP", q_a, t_a)]:
                        Ra = core.R_of(q)
                        # penetration of the *estimated* pose
                        xe = (Ra @ V.T).T + tt
                        pen = max(0.0, -(xe @ n + d).min()) * 1000.0
                        viol = core.max_viol(A, B, q, tt)
                        rows.append(dict(frame=frame, img=img, obj=oid, bias_px=bias_px, method=name,
                                         pen_mm=pen, rot_deg=core.rot_deg(q, core.q_from_R(R)),
                                         trans_mm=core.trans_mm(tt, t), feas=viol <= 1e-6,
                                         viol=viol, time_ms=t_solve * 1000.0 / 4.0,
                                         J=core.obj_value(q, tt, M0, D0, G0)))
                    # certificate for ALM only (slow)
                    t0 = time.perf_counter()
                    try:
                        sres = shor_bound(M0, D0, G0, A, B)
                        val = float(sres["value"])
                    except Exception as ex:
                        print("cert fail", ex)
                        val = float("nan")
                    t_cert = time.perf_counter() - t0
                    t0 = time.perf_counter()
                    try:
                        sres_rlt = shor_bound(M0, D0, G0, A, B, add_rlt=True)
                        val_rlt = float(sres_rlt["value"])
                    except Exception as ex:
                        print("cert RLT fail", ex)
                        val_rlt = float("nan")
                    t_cert_rlt = time.perf_counter() - t0
                    for rr in rows[-4:]:
                        rr["shor"] = val
                        rr["cert"] = bool(np.isfinite(val) and (rr["J"] - val <= 1e-6) and rr["feas"])
                        rr["shor_rlt"] = val_rlt
                        rr["cert_rlt"] = bool(np.isfinite(val_rlt) and (rr["J"] - val_rlt <= 1e-6) and rr["feas"])
                        # two-sided diagnostics: a sound lower bound needs Shor <= J, so the
                        # one-sided flags above are an upper bound on the sound cert rate.
                        rr["shor_minus_J"] = float(val - rr["J"]) if np.isfinite(val) else float("nan")
                        rr["gap_two_sided"] = float(abs(rr["J"] - val)) if np.isfinite(val) else float("nan")
                        rr["cert_two_sided"] = bool(np.isfinite(val) and abs(rr["J"] - val) <= 1e-6 and rr["feas"])
                        rr["shor_rlt_minus_J"] = float(val_rlt - rr["J"]) if np.isfinite(val_rlt) else float("nan")
                        rr["gap_rlt_two_sided"] = float(abs(rr["J"] - val_rlt)) if np.isfinite(val_rlt) else float("nan")
                        rr["cert_rlt_two_sided"] = bool(np.isfinite(val_rlt) and abs(rr["J"] - val_rlt) <= 1e-6 and rr["feas"])
                        rr["time_plane_s"] = t_plane
                        rr["time_cert_s"] = t_cert
                        rr["time_cert_rlt_s"] = t_cert_rlt
                    t_plane_all.append(t_plane); t_solve_all.append(t_solve)
                    t_cert_all.append(t_cert); t_cert_rlt_all.append(t_cert_rlt)
        print("frame", frame, "done", flush=True)
    wall = time.perf_counter() - wall0
    json.dump(rows, open(OUT / "raw.json", "w"), indent=2, default=float)
    meta = dict(dataset=DATASET, frames=FRAMES, max_img=MAX_IMG, obj_ids=obj_ids,
                plane_calib=PLANE_CALIB, seed=SEED, n_trials=len(rows) // 4,
                n_poses=n_poses, wall_s=wall,
                t_plane_mean_s=float(np.mean(t_plane_all)) if t_plane_all else None,
                t_solve_mean_s=float(np.mean(t_solve_all)) if t_solve_all else None,
                t_cert_mean_s=float(np.mean(t_cert_all)) if t_cert_all else None,
                t_cert_rlt_mean_s=float(np.mean(t_cert_rlt_all)) if t_cert_rlt_all else None)
    json.dump(meta, open(OUT / "meta.json", "w"), indent=2)
    write_table(rows, meta)


if __name__ == "__main__":
    main()
