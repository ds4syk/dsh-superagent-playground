#!/usr/bin/env python3
"""P2 real-data table: constrained 6-DoF PnP on BOP LINEMOD / LM-O / YCB-Video.

Dataset loading is checked against the GT bounding boxes (projection of the
model with the GT pose must match scene_gt_info bbox_obj).  The support plane
is estimated from the background depth image (RANSAC) and used for the
non-penetration constraints.  The pose layer sees real object meshes, real
camera intrinsics and real table planes; pixel noise / downward pixel bias
create the penetration that the constrained layer must remove.

This is a controlled layer experiment, not a learned detector: 2D-3D
correspondences are generated by projecting the object model at the GT pose,
then perturbed with pixel noise.  No claim about a real front-end is made.

Usage
-----
    python run_bop.py <dataset>            # lm | lmo | ycbv
    # or via env knobs (all optional, defaults reproduce the published table):
    BOP_MAX_FRAMES=12 BOP_MAX_IMG=2 BOP_OBJ_IDS=4,3,1 python run_bop.py ycbv

Env
---
BOP_DATA_ROOT   root containing <dataset>/    (default /mnt/storage1/syk/data/bop)
BOP_OUT_DIR     output dir (abs, or relative to this script)
BOP_MAX_FRAMES  number of frame dirs (sorted) to use  (default 9)
BOP_MAX_IMG     images per frame                      (default 2)
BOP_OBJ_IDS     comma separated object ids (default: 3 most frequent in frames)
BOP_PLANE_CALIB "always" (default, GT lowest point touches the plane) or
                "if_penetrating" (legacy run_linemod rule: shift only if below)
BOP_SEED        RNG seed (default 20261127)
"""
