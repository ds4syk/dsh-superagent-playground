#!/usr/bin/env python3
"""pi as a period: Legendre family, Picard-Fuchs, monodromy, CM point (corrected)."""
from mpmath import mp, mpf, mpc, pi, sqrt, quad, log, exp, gamma, hyper, diff, fabs, nstr
import sympy as sp
mp.dps = 40

lam = sp.symbols('lam')
print("(1) 2*pi*i = oint dz/z =", nstr(2j*pi, 14), "  (period of Z(1))")

# PF equation verified with mpmath.diff on the actual 2F1
print("\n(2) Picard-Fuchs residual lam(1-lam)F''+(1-2lam)F'-(1/4)F,  F=2F1(1/2,1/2;1;lam)")
f = lambda t: hyper([mpf(1)/2, mpf(1)/2],[1], t)
for t in [mpf('0.13'), mpf('0.6'), mpf('-0.4'), mpc('0.2','0.1')]:
    r = t*(1-t)*diff(f,t,2) + (1-2*t)*diff(f,t) - f(t)/4
    print(f"    lam={nstr(t,6):>12}  residual={nstr(r,4)}")

print("\n(3) indicial equation at lam=0:  r^2=0  ->  exponents 0,0  -> unipotent monodromy")
print("    second solution: F2 = F*log(lam) + G,   PF(G) = F - 2(1-lam)F'")
# solve PF(G)=F-2(1-lam)F' for G=sum g_n lam^n, g0 free
M = 12
cs = [sp.Rational(int(sp.binomial(2*n,n)), 4**n) for n in range(M+2)]
Fs = sum(cs[n]*lam**n for n in range(M+2))
G = sum(sp.Symbol(f'g{n}')*lam**n for n in range(M))
rhs = sp.expand(Fs - 2*(1-lam)*sp.diff(Fs,lam))
lhsop = sp.expand(lam*(1-lam)*sp.diff(G,lam,2) + (1-2*lam)*sp.diff(G,lam) - G/4)
poly = sp.Poly(sp.expand((lhsop - rhs)*lam**2), lam)
coeffs = poly.all_coeffs()[::-1]     # ascending
sol = {}
for e in coeffs:
    e2 = sp.expand(e.subs(sol))
    free = [s for s in e2.free_symbols if str(s).startswith('g')]
    if len(free)==1 and e2 != 0:
        v = sp.solve(sp.Eq(e2,0), free[0])
        if v: sol[free[0]] = sp.simplify(v[0])
G = sp.expand(G.subs(sol))
print("    G(lam) =", sp.series(G, lam, 0, 6).removeO(), " (g0 free)")
print("    monodromy around lam=0: F -> F,  F2 -> F2 + 2*pi*i*F  =>  M = [[1,2*pi*i],[0,1]]")

print("\n(4) exact period of the vanishing cycle:  int_0^lam dx/sqrt(x(x-1)(x-lam)) = 2K(lam) -> pi")
def lhs(l): return quad(lambda x: 1/sqrt(x*(x-1)*(x-l)), [0, l/2, l])
def K(l):  return quad(lambda th: 1/sqrt(1-l*mp.sin(th)**2), [0, pi/2])
for l in [mpf('1e-2'), mpf('1e-4'), mpf('1e-6'), mpf('1e-8'), mpf('1e-10')]:
    print(f"    lam={float(l):9.1e}  integral={nstr(lhs(l),20)}   pi={nstr(pi,20)}")
print("    limit = 2K(0) = pi.  Nodal degeneration: y^2=x^2(x-1), y~+-ix, dx/y~-+dx/x,")
print("    residues -+i, and pi = 2*pi*i*(1/(2i)):  the period is 2*pi*i times a rational.")

print("\n(5) CM point lam=-1 (square lattice, j=1728):")
print("    K(-1) =", nstr(K(mpf(-1)), 20))
print("    Gamma(1/4)^2/(4*sqrt(2*pi)) =", nstr(gamma(mpf(1)/4)**2/(4*sqrt(2*pi)), 20))
print("    lemniscate varpi =", nstr(gamma(mpf(1)/4)**2/(2*sqrt(2*pi)), 20), " = 2*K(-1)")
print("    => the CM period is a Gamma(1/4)-value; the cusp period is pi.")
print("    Diophantine status: pi ~ linear forms in logs (Baker); Gamma(1/4) ~ Nesterenko only.")

print("\n(6) period algebra generated by the classical periods is Q[pi]:")
from mpmath import bernfrac, zeta, factorial
for n in range(1,5):
    B = bernfrac(2*n)
    val = sp.Rational(int(B[0]),int(B[1]))*sp.Integer(2)**(2*n)*(-1)**(n+1)/sp.Integer(2)/sp.Integer(int(sp.factorial(2*n)))
    print(f"    zeta({2*n})/pi^{2*n} =", val, "  check", nstr(zeta(2*n)/pi**(2*n), 16))
print("    => any Q-linear form in the periods reduces to a polynomial in pi: Q[pi].")
